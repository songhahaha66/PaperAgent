const assert=require('node:assert/strict')
const {loadModule,vue,flush}=require('./moduleHarness.cjs')
const {hostRenderer}=require('./vueHost.cjs')
const text=n=>[n.text||'',...(n.children||[]).map(text)].join('')
const copy={'@/lang/studio':{useStudioCopy:()=>({isZh:vue.ref(true)})}}
;(async()=>{
 const module=await loadModule('src/components/ResearchOutcome.vue',{vue,...copy},{},true)
 const host=hostRenderer(),outcome=vue.reactive({id:'arbitrary-task',task_id:'arbitrary-task',title:'不同领域的成果',computation:'succeeded',availability:'current',checking:'service_failed',method:null,results:[{id:'R8',name:'opaque_v',kind:'number',value:'2.5',unit:'',description:'',run_id:'run_1'}],claims:[],issues:[],sources:[],next_step:null,history:[]})
 const app=host.renderer.createApp({setup:()=>()=>vue.h(module.default,{workId:'one',outcome,runs:[]})});app.mount(host.root);await flush()
 assert.match(text(host.root),/检查服务故障，未通过/)
 assert.match(text(host.root),/opaque_v/)
 assert.doesNotMatch(text(host.root),/缺少含义说明/)
 assert.match(text(host.root),/没有下一步决策或理由/)
 assert.doesNotMatch(text(host.root),/RMSE|销量|万元|检查已完成/)
 outcome.results=[{id:'R9',name:'预测值',kind:'number',value:'1234.57',unit:'万千瓦时',description:'',run_id:'run_1'}];await flush()
 assert.match(text(host.root),/预测值/);assert.match(text(host.root),/万千瓦时/)
 assert.doesNotMatch(text(host.root),/缺少含义说明|Meaning was not recorded/,'An optional description is not required to display a registered measurement')
 outcome.checking='unreviewed';outcome.availability='legacy';await flush()
 assert.match(text(host.root),/尚未完成审查/);assert.match(text(host.root),/旧成果，版本待核实/)
 app.unmount()
 const project={research_id:'draft',main:'paper.tex',version:'v1',files:[],compile:{state:'untracked',message:'尚未编译'},pdf_available:false,sources:[],threads:[],executions:[],changes:[]}
 const reads=[]
 const paper=await loadModule('src/components/PaperEditor.vue',{vue,...copy,'@/api/paper':{paperProjectAPI:{read:async(work)=>{reads.push(work);return project}}}},{},true)
 const empty=hostRenderer(),paperApp=empty.renderer.createApp(paper.default,{workId:'new',latex:true,snapshot:{has_research:true,artifacts:[]}});paperApp.mount(empty.root);await flush()
 assert.deepEqual(reads,['new'])
 assert.match(text(empty.root),/论文草稿尚未生成/)
 assert.match(text(empty.root),/无需等待整项研究审查完成/)
 assert.match(text(empty.root),/阅读|源码|刷新/)
 assert.doesNotMatch(text(empty.root),/选择章节|版本与候选历史|局部提案请求历史|生成修改对比/)
 assert.equal(empty.find(n=>n.kind==='textarea'),undefined)
 paperApp.unmount()
 // A draft uses the file project even while the research snapshot has no published artifacts.
 project.files=[{path:'paper.tex',version:'file-v1',text:'未验收的草稿正文',size:30}]
 const draftModule=await loadModule('src/components/PaperEditor.vue',{vue,'@/api/paper':{paperProjectAPI:{read:async()=>project}}})
 const scope=vue.effectScope()
 const draft=scope.run(()=>draftModule.default.setup({workId:'new',latex:true,snapshot:{has_research:true,artifacts:[]}},{expose(){},emit(){}}))
 await flush()
 assert.equal(draft.project.value.files.length,1)
 draft.setView('source')
 assert.equal(draft.view.value,'source')
 assert.equal(draft.draft.value,'未验收的草稿正文')
 assert.equal(draft.selectedFile.value.path,'paper.tex')
 scope.stop()
 console.log('PASS: generic results retain evidence through service failure; empty papers and unpublished drafts use the file project API')
})().catch(e=>{console.error(e);process.exitCode=1})
