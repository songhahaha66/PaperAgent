const assert = require('node:assert/strict')
const { loadModule } = require('./moduleHarness.cjs')
;(async () => {
  const {applyAgentEvent,visibleItems}=await loadModule('src/utils/conversationTimeline.ts',{})
  const base={thread_id:'lead',turn_id:'turn',status:'running',started_at:1}
  const text={...base,id:'text',sequence:1,type:'agentMessage',phase:'commentary',text:'Before {"type":"confirm"}'}
  const tool={...base,id:'tool',sequence:2,type:'commandExecution',tool_name:'run_python',call_id:'call',label:'计算'}
  const update=(seq,item,method='item/started')=>({reply_id:'reply',chat_task_id:'task',thread_id:'lead',turn_id:'turn',event:{seq,method,thread_id:item.thread_id,turn_id:item.turn_id,item}})
  let message={id:'reply',content:'',items:[]}
  message=applyAgentEvent(message,update(1,text))
  message=applyAgentEvent(message,update(2,tool))
  message=applyAgentEvent(message,update(3,{...tool,status:'failed',message:'bad data',finished_at:3},'item/completed'))
  assert.equal(message.items.length,2)
  assert.equal(message.items[1].status,'failed')
  assert.equal(applyAgentEvent(message,update(2,tool)),message,'old replay cannot undo completion')
  assert.equal(applyAgentEvent(message,update(3,tool)),message,'duplicate replay is idempotent')
  message=applyAgentEvent(message,update(4,{...tool,id:'retry',sequence:3,status:'completed'},'item/completed'))
  assert.equal(message.items[1].status,'failed','a successful retry preserves prior failure')
  message=applyAgentEvent(message,update(5,{...tool,id:'child',thread_id:'child-thread',turn_id:'child-turn',sequence:1}))
  assert.equal(visibleItems(message).map(i=>i.id).join(','),'text,tool,retry','child thread never flattens into parent')
  message=applyAgentEvent(message,{reply_id:'reply',chat_task_id:'task',thread_id:'lead',turn_id:'turn',event:{seq:6,method:'turn/completed',thread_id:'child-thread',turn_id:'child-turn',turn:{id:'child-turn',status:'completed'}}})
  assert.equal(message.metadata.status,'running','child completion does not finish parent')
  message=applyAgentEvent(message,{reply_id:'reply',chat_task_id:'task',thread_id:'lead',turn_id:'turn',event:{seq:7,method:'turn/completed',thread_id:'lead',turn_id:'turn',turn:{id:'turn',status:'completed'}}})
  assert.equal(message.metadata.status,'completed')
  assert.equal(message.content,text.text,'JSON-looking prose stays authored text')
  const loaded=JSON.parse(JSON.stringify(message))
  assert.equal(applyAgentEvent(loaded,update(6,tool)),loaded,'history and live stream share the same cursor')
  assert.equal(visibleItems({id:'old',content:'',segments:[tool]}).length,0,'retired protocol has no compatibility renderer')
  console.log('PASS: typed Item reducer, replay, turn isolation and terminal states')
})().catch(e=>{console.error(e);process.exitCode=1})
