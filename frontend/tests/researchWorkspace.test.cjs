const assert=require('node:assert/strict')
const {hostRenderer}=require('./vueHost.cjs')
const {loadModule,vue,flush}=require('./moduleHarness.cjs')
;(async()=>{
 const runtime=await loadModule('src/components/ResearchRuntime.vue',{vue})
 const scope=vue.effectScope()
 const snapshot=vue.reactive({runtime:{actions:[],models:[],history:[]},questions:[],experiments:[],results:[],runs:[],has_research:true,execution_reason:{message:'原始运行诊断已保存'}})
 const state=scope.run(()=>runtime.default.setup({snapshot,workStatus:'paused'},{emit(){},expose(){}}))
 assert.equal(state.paused.value,true)
 assert.equal(state.current.value,undefined,'An old fault must not become a current running call')
 snapshot.runtime.history=[{id:'old',kind:'action_failed',label:'先前操作未完成',recorded_at:1,reason:'历史故障',artifact_refs:[],judgments:[]}]
 assert.equal(state.history.value.length,1,'Historical faults remain inspectable without being current execution')
 const calls=[]
 const library=await loadModule('src/components/ResearchExperiences.vue',{vue,'tdesign-vue-next':{DialogPlugin:{}},'@/api/experiences':{experienceAPI:{read:async()=>({cards:[],enabled:true}),transition:async(...args)=>calls.push(args)}},'@/lang/studio':{useStudioCopy:()=>({isZh:vue.ref(true)})}})
 const personal=scope.run(()=>library.default.setup({},{emit(){},expose(){}}));await flush()
 await personal.transition({id:'E1',version:3},'adopt')
 assert.equal(calls[0][0],'E1');assert.equal(calls[0][1],'adopt');assert.equal(calls[0][2],3)
 const progress=await loadModule('src/components/ResearchProgress.vue',{vue}, {}, true)
 const status=await loadModule('src/components/ResearchStatus.vue',{vue,'./ResearchProgress.vue':{default:progress.default}}, {}, true)
 const page=vue.ref({...snapshot,work_status:'paused',delivery_summary:{state:'incomplete',stage:'export',label:'报告导出未完成，已有计算和文件已保留'},
   questions:[{id:'q1',title:'结果可信吗？',experiment_ids:[],judgment:'',judgments:[],limitations:[],issues:[],sources:[],artifact_refs:[],answer_gaps:['还缺独立验证']}],artifacts:[],claims:[]})
 const host=hostRenderer(),actions=[]
 const app=host.renderer.createApp({render:()=>vue.h(status.default,{workId:'work',snapshot:page.value,workStatus:'paused',actionLabel:'继续',onAction:()=>actions.push('resume')})})
 const text=node=>[node.text||'',...(node.children||[]).map(text)].join('')
 app.mount(host.root);await flush()
 assert.match(text(host.root),/报告导出未完成/)
 assert.match(text(host.root),/当前判断待补全/)
 assert.match(text(host.root),/还缺独立验证/)
 host.find(node=>node.kind==='button'&&text(node).trim()==='继续').props.onClick()
 assert.deepEqual(actions,['resume'],'the status surface forwards the actual progress action')
 page.value={...page.value,delivery_summary:{state:'completed',stage:'render',label:'报告已生成，可查看和下载'}}
 await flush();assert.match(text(host.root),/报告已生成，可查看和下载/);assert.doesNotMatch(text(host.root),/导出未完成/)
 app.unmount()
 scope.stop()
 console.log('PASS: research surfaces share the new model; runtime faults and personal adoption remain separate')
})().catch(e=>{console.error(e);process.exitCode=1})
