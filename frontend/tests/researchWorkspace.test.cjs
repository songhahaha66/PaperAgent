const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {loadModule,vue,flush}=require('./moduleHarness.cjs')
;(async()=>{
 const source=name=>fs.readFileSync(path.join(__dirname,'../src',name),'utf8')
 const work=source('views/Work.vue')
 assert(!work.includes('ResearchOverview')&&!work.includes('ResearchComparisons'))
 assert(work.includes('ResearchStatus')&&work.includes('ResearchMaterials'))
 assert(work.includes("openPanel('materials'")&&!work.includes("openPanel('literature'"),'header opens the current materials panel')
 assert(!fs.existsSync(path.join(__dirname,'../src/components/ResearchEvidence.vue')))
 const status=await loadModule('src/components/ResearchStatus.vue',{vue,'@/api/researchSetup':{executionRecoveryAPI:{}}})
 const scope=vue.effectScope()
 const state=scope.run(()=>status.default.setup({workId:'A',snapshot:{feedback:[{id:'finding',status:'confirmed'}],faults:[{id:'timeout',status:'confirmed',category:'service'},{id:'closed',status:'resolved'}]}},{emit(){},expose(){}}))
 assert.equal(state.faults.value.length,1);assert.equal(state.faults.value[0].id,'timeout')
 const calls=[]
 const library=await loadModule('src/components/ResearchExperiences.vue',{vue,'tdesign-vue-next':{DialogPlugin:{}},'@/api/experiences':{experienceAPI:{read:async()=>({cards:[],enabled:true}),transition:async(...args)=>calls.push(args)}},'@/lang/studio':{useStudioCopy:()=>({isZh:vue.ref(true)})}})
 const personal=scope.run(()=>library.default.setup({},{emit(){},expose(){}}));await flush()
 await personal.transition({id:'E1',version:3},'adopt')
 assert.equal(calls[0][0],'E1');assert.equal(calls[0][1],'adopt');assert.equal(calls[0][2],3)
 scope.stop()
 console.log('PASS: research surfaces share the new model; runtime faults and personal adoption remain separate')
})().catch(e=>{console.error(e);process.exitCode=1})
