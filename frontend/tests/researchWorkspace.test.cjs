const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {loadModule,vue,flush}=require('./moduleHarness.cjs')
;(async()=>{
 const source=name=>fs.readFileSync(path.join(__dirname,'../src',name),'utf8')
 const work=source('views/Work.vue')
 assert(!work.includes('ResearchOverview')&&!work.includes('ResearchComparisons'))
 assert(work.includes('ResearchStatus')&&work.includes('ResearchResultViewer'))
 assert(!work.includes('ResearchMaterials'))
 assert(source('components/ResearchStatus.vue').includes('ResearchProgress'))
 assert(source('components/ResearchResultViewer.vue').includes('ResearchExperiment'))
 assert(work.includes("openPanel('files'")&&!work.includes("openPanel('materials'"),'header opens the current file panel')
 assert(!fs.existsSync(path.join(__dirname,'../src/components/ResearchEvidence.vue')))
 const runtime=await loadModule('src/components/ResearchRuntime.vue',{vue})
 const scope=vue.effectScope()
 const snapshot=vue.reactive({runtime:{actions:[],models:[],history:[]},questions:[],experiments:[],results:[],runs:[],has_research:true,execution_reason:{message:'原始运行诊断已保存'}})
 const state=scope.run(()=>runtime.default.setup({snapshot,workStatus:'paused'},{emit(){},expose(){}}))
 assert.equal(state.paused.value,true)
 assert.equal(state.current.value,undefined,'An old fault must not become a current running call')
 snapshot.runtime.history=[{id:'old',kind:'action_failed',label:'先前操作未完成',recorded_at:1,reason:'历史故障',artifact_refs:[],judgments:[]}]
 assert.equal(state.history.value.length,1,'Historical faults remain inspectable without being current execution')
 const calls=[]
 const library=await loadModule('src/components/ResearchExperiences.vue',{vue,'tdesign-vue-next':{DialogPlugin:{}},'@/api/experiences':{experienceAPI:{read:async()=>({cards:[],enabled:true}),transition:async(...args)=>calls.push(args)}},'@/lang/studio':{useStudioCopy:()=>({isZh:vue.ref(true)})}})
 const personal=scope.run(()=>library.default.setup({},{emit(){},expose(){}}));await flush()
 await personal.transition({id:'E1',version:3},'adopt')
 assert.equal(calls[0][0],'E1');assert.equal(calls[0][1],'adopt');assert.equal(calls[0][2],3)
 scope.stop()
 console.log('PASS: research surfaces share the new model; runtime faults and personal adoption remain separate')
})().catch(e=>{console.error(e);process.exitCode=1})
